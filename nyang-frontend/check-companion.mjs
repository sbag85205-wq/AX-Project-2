assert.equal(makeSchedule('half','2026-10-19')[0].date,'2026-10-18');
assert.equal(makeSchedule('education','2026-10-19','2026-10-23')[0].date,'2026-10-12');
assert.equal(makeSchedule('education','2026-10-19','2026-10-23')[2].date,'2026-10-26');
assert.equal(makeSchedule('settle','2026-10-23')[0].deadline,'2026-10-30');
assert.throws(()=>makeSchedule('annual','2026-02-30'));
