assert.throws(()=>rewardTransition(s,{type:'feed',ids:['d','e','f']}));
s=rewardTransition(s,{type:'collect',id:'a'});assert.equal(s.hearts,1);
s=rewardTransition(s,{type:'collect',id:'a'});assert.equal(s.hearts,1);
assert.throws(()=>rewardTransition(s,{type:'buy',id:'ribbon'}));
for(const id of ['b','c'])s=rewardTransition(s,{type:'collect',id});
