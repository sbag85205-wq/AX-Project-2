s=rewardTransition(s,{type:'buy',id:'ribbon'});assert.equal(s.hearts,0);assert.equal(s.owned.length,1);
s=rewardTransition(s,{type:'equip',id:null});assert.equal(s.equipped,null);
assert.throws(()=>rewardTransition(s,{type:'equip',id:'crown'}));
assert.deepEqual(normalizeRewards(JSON.parse(JSON.stringify(s))),s);
const old=s;const after=rewardTransition(s,{type:'question'});assert.equal(old.points,0);assert.equal(after.points,10);
assert.equal(scheduleTypeFor({kind:'unknown'}),null);
assert.equal(scheduleTypeFor({kind:'scope',target:'trip'}),null);
assert.equal(scheduleTypeFor({kind:'answer',id:'annual'}),'annual');
