import assert from 'node:assert/strict';
import {initialRewards,rewardTransition,normalizeRewards,makeSchedule,mergeSchedule,scheduleTypeFor,petOutcome,PET_LIKE_CHANCE,PET_BONUS_CHANCE,PET_BONUS_POINTS,PET_COOLDOWN_MS} from './public/companion.js';
