assert.equal(mergeSchedule(added.tasks,plan,()=>String(++n)).added,0);
const legacy=plan.items.map(t=>({...t,key:`${plan.start}:${plan.end}:${t.ref}`}));
assert.equal(mergeSchedule(legacy,plan,()=>String(++n)).added,0);
assert.equal(petOutcome(0,0),'bonus');
assert.equal(petOutcome(PET_LIKE_CHANCE-Number.EPSILON,PET_BONUS_CHANCE-Number.EPSILON),'bonus');
assert.equal(petOutcome(0,PET_BONUS_CHANCE),'like');
assert.equal(petOutcome(PET_LIKE_CHANCE,0),'dislike');
assert.equal(petOutcome(.999,.999),'dislike');
for(const bad of [-1,1,NaN,Infinity,'0'])assert.throws(()=>petOutcome(bad,0));
// A uniform grid verifies the conditional 3% rate independently of Math.random.
const outcomes=Array.from({length:10000},(_,i)=>petOutcome(Math.floor(i/100)/100,(i%100)/100));
assert.equal(outcomes.filter(x=>x==='bonus').length,180);
assert.equal(outcomes.filter(x=>x!=='dislike').length,6000);
const petBase={...initialRewards(),points:12,hearts:2,pending:['h'],owned:['ribbon'],equipped:'ribbon'};
const stroke={type:'pet',id:'stroke-a',at:10000,likeRoll:0,bonusRoll:0};
const lucky=rewardTransition(petBase,stroke);
assert.equal(lucky.points,12+PET_BONUS_POINTS);assert.equal(lucky.pettings,1);assert.equal(lucky.petBonuses,1);
assert.equal(petBase.points,12);assert.deepEqual(lucky.pending,['h']);assert.equal(lucky.hearts,2);assert.equal(lucky.equipped,'ribbon');
assert.deepEqual(rewardTransition(lucky,stroke),lucky);
assert.deepEqual(rewardTransition(lucky,{...stroke,id:'stroke-b',at:10000+PET_COOLDOWN_MS-1}),lucky);
assert.deepEqual(rewardTransition(lucky,{...stroke,id:'stroke-old',at:9000}),lucky);
assert.deepEqual(rewardTransition(lucky,{...stroke,at:99999}),lucky);
const restored=normalizeRewards(JSON.parse(JSON.stringify(lucky)));
assert.deepEqual(restored,lucky);
assert.deepEqual(rewardTransition(restored,{...stroke,id:'reload',at:10001}),lucky);
const liked=rewardTransition(restored,{...stroke,id:'stroke-b',at:10000+PET_COOLDOWN_MS,bonusRoll:.5});
assert.equal(liked.points,lucky.points);assert.equal(liked.pettings,2);
const disliked=rewardTransition(liked,{...stroke,id:'stroke-c',at:10000+PET_COOLDOWN_MS*2,likeRoll:.9});
assert.equal(disliked.points,lucky.points);assert.equal(disliked.petBonuses,1);assert.equal(disliked.pettings,3);
