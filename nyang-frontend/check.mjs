import assert from 'node:assert/strict';
import {businessBefore,businessAfter,makePlan,resolveQuestion,reference,faq,answers} from './public/core.js';
assert.equal(businessBefore('2026-10-19',3),'2026-10-14');
assert.equal(businessBefore('2027-01-04',3),'2026-12-30');
assert.equal(businessAfter('2026-10-23'),'2026-10-26');
const plan=makePlan('2026-10-23','2026-10-23');
assert.equal(plan[0].deadline,'2026-10-20');
assert.equal(plan[3].date,'2026-10-26');
assert.equal(plan[3].deadline,'2026-10-30');
assert.throws(()=>makePlan('2026-10-23','2026-10-22'));
assert.throws(()=>makePlan('2026-02-31','2026-03-04'));
assert.equal(resolveQuestion('자차로 출장 가도 돼?','hr').kind,'scope');
assert.equal(resolveQuestion('해외 출장 준비 일정을 짜줘','trip').kind,'unknown');
assert.equal(resolveQuestion('내 잔여 연차는 얼마야?','hr').kind,'unknown');
assert.equal(resolveQuestion('오늘 날씨 알려줘','life').kind,'unknown');
assert.equal(resolveQuestion('출장 준비 일정 짜줘','trip').kind,'plan');
for(const pairs of Object.values(faq))for(const [,id] of pairs)if(id!=='plan')assert.ok(answers[id]);
for(const a of Object.values(answers))for(const id of a.refs)assert.ok(reference(id));
for(const item of plan)assert.ok(reference(item.ref));
